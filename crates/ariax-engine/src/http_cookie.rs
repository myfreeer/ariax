pub const DEFAULT_HTTP_COOKIE_TOTAL_ENTRIES: usize = 3000;
pub const MAX_HTTP_COOKIE_ENTRIES_PER_DOMAIN: usize = 180;
pub const MAX_HTTP_COOKIE_BYTES_PER_DOMAIN: usize = 64 * 1024;
pub const MAX_HTTP_COOKIE_BYTES: usize = 4096;
pub const MAX_HTTP_COOKIE_HEADER_BYTES: usize = 16 * 1024;
pub const MAX_HTTP_PSL_BYTES: usize = 4 * 1024 * 1024;
pub const MAX_HTTP_PSL_SNAPSHOT_ID_BYTES: usize = 128;
pub const MAX_HTTP_COOKIE_FILE_BYTES: usize = 8 * 1024 * 1024;
pub const MAX_HTTP_COOKIE_FILE_LINES: usize = 16 * 1024;
pub const HTTP_PSL_SNAPSHOT_ID: &str = "mozilla-psl-2026-07-25-e1b8015c";
pub const HTTP_PSL_SHA256: [u8; 32] = [
    0x08, 0x4a, 0x56, 0x74, 0xd7, 0x7c, 0x1d, 0x14, 0x90, 0x0b, 0x16, 0xda, 0x5f, 0xc8, 0xaf, 0xee,
    0x97, 0x65, 0xaf, 0x2f, 0x00, 0xa6, 0x38, 0x55, 0x2a, 0x8c, 0x7a, 0xa1, 0x8f, 0x44, 0xae, 0x81,
];

const BUNDLED_HTTP_PSL: &[u8] = include_bytes!("../../../assets/public-suffix-list.dat");
const NETSCAPE_COOKIE_HEADER: &str = "# Netscape HTTP Cookie File\n# This file was generated by ariax. Do not edit while ariax is running.\n";
const HTTP_ONLY_PREFIX: &str = "#HttpOnly_";
static COOKIE_TEMP_ID: AtomicU64 = AtomicU64::new(1);

#[derive(Clone, Copy, Debug, Eq, PartialEq)]
pub struct HttpCookieLimits {
    pub total_entries: usize,
    pub entries_per_domain: usize,
    pub bytes_per_domain: usize,
    pub cookie_bytes: usize,
    pub header_bytes: usize,
}

impl Default for HttpCookieLimits {
    fn default() -> Self {
        Self {
            total_entries: DEFAULT_HTTP_COOKIE_TOTAL_ENTRIES,
            entries_per_domain: MAX_HTTP_COOKIE_ENTRIES_PER_DOMAIN,
            bytes_per_domain: MAX_HTTP_COOKIE_BYTES_PER_DOMAIN,
            cookie_bytes: MAX_HTTP_COOKIE_BYTES,
            header_bytes: MAX_HTTP_COOKIE_HEADER_BYTES,
        }
    }
}

impl HttpCookieLimits {
    fn validate(self) -> Result<Self, HttpCookieError> {
        if self.total_entries == 0
            || self.total_entries > DEFAULT_HTTP_COOKIE_TOTAL_ENTRIES
            || self.entries_per_domain == 0
            || self.entries_per_domain > MAX_HTTP_COOKIE_ENTRIES_PER_DOMAIN
            || self.bytes_per_domain == 0
            || self.bytes_per_domain > MAX_HTTP_COOKIE_BYTES_PER_DOMAIN
            || self.cookie_bytes == 0
            || self.cookie_bytes > MAX_HTTP_COOKIE_BYTES
            || self.header_bytes == 0
            || self.header_bytes > MAX_HTTP_COOKIE_HEADER_BYTES
        {
            return Err(HttpCookieError::InvalidLimits);
        }
        Ok(self)
    }
}

