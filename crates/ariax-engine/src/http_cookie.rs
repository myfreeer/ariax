struct NetscapeCookieRecord {
    request: Url,
    cookie: cookie::Cookie<'static>,
}

fn parse_netscape_cookie_line(line: &str) -> Result<Option<NetscapeCookieRecord>, HttpCookieError> {
    if line.len() > MAX_HTTP_COOKIE_BYTES * 3 {
        return Err(HttpCookieError::CookieFileSyntax);
    }
    let (http_only, line) = line
        .strip_prefix(HTTP_ONLY_PREFIX)
        .map_or((false, line), |line| (true, line));
    let fields = line.split('\t').collect::<Vec<_>>();
    let [
        domain,
        include_subdomains,
        path,
        secure,
        expires,
        name,
        value,
    ] = fields.as_slice()
    else {
        return Err(HttpCookieError::CookieFileSyntax);
    };
    if domain.is_empty()
        || !netscape_field_is_safe(domain)
        || !path.starts_with('/')
        || !netscape_field_is_safe(path)
        || !valid_cookie_name(name)
        || !valid_cookie_value(value)
    {
        return Err(HttpCookieError::CookieFileSyntax);
    }
    let include_subdomains = parse_netscape_bool(include_subdomains)?;
    let secure = parse_netscape_bool(secure)?;
    let expires = expires
        .parse::<u64>()
        .map_err(|_| HttpCookieError::CookieFileSyntax)?;
    if expires != 0
        && expires
            <= SystemTime::now()
                .duration_since(SystemTime::UNIX_EPOCH)
                .map_err(|_| HttpCookieError::CookieFileSyntax)?
                .as_secs()
    {
        return Ok(None);
    }
    let host = domain.trim_start_matches('.');
    if host.is_empty() {
        return Err(HttpCookieError::CookieFileSyntax);
    }
    let authority = if host.parse::<std::net::Ipv6Addr>().is_ok() {
        format!("[{host}]")
    } else {
        host.to_owned()
    };
    let scheme = if secure { "https" } else { "http" };
    let request = Url::parse(&format!("{scheme}://{authority}/"))
        .map_err(|_| HttpCookieError::CookieFileSyntax)?;
    if request.host_str().is_none_or(str::is_empty) {
        return Err(HttpCookieError::CookieFileSyntax);
    }

    let mut cookie = cookie::Cookie::new((*name).to_owned(), (*value).to_owned());
    cookie.set_path((*path).to_owned());
    cookie.set_secure(secure);
    cookie.set_http_only(http_only);
    if include_subdomains {
        cookie.set_domain(host.to_owned());
    }
    if expires != 0 {
        let timestamp = i64::try_from(expires).map_err(|_| HttpCookieError::CookieFileSyntax)?;
        let expiration = cookie::time::OffsetDateTime::from_unix_timestamp(timestamp)
            .map_err(|_| HttpCookieError::CookieFileSyntax)?;
        cookie.set_expires(expiration);
    }
    Ok(Some(NetscapeCookieRecord { request, cookie }))
}

fn parse_netscape_bool(value: &str) -> Result<bool, HttpCookieError> {
    match value {
        "TRUE" => Ok(true),
        "FALSE" => Ok(false),
        _ => Err(HttpCookieError::CookieFileSyntax),
    }
}

fn valid_cookie_name(value: &str) -> bool {
    !value.is_empty()
        && value.len() <= MAX_HTTP_COOKIE_BYTES
        && value.bytes().all(|byte| {
            byte.is_ascii_alphanumeric()
                || matches!(
                    byte,
                    b'!' | b'#'
                        | b'$'
                        | b'%'
                        | b'&'
                        | b'\''
                        | b'*'
                        | b'+'
                        | b'-'
                        | b'.'
                        | b'^'
                        | b'_'
                        | b'`'
                        | b'|'
                        | b'~'
                )
        })
}

fn valid_cookie_value(value: &str) -> bool {
    value.len() <= MAX_HTTP_COOKIE_BYTES
        && value.bytes().all(|byte| {
            !byte.is_ascii_control() && !matches!(byte, b' ' | b'"' | b',' | b';' | b'\\' | b'\t')
        })
}

fn netscape_field_is_safe(value: &str) -> bool {
    value.len() <= MAX_HTTP_COOKIE_BYTES
        && !value.is_empty()
        && !value
            .bytes()
            .any(|byte| byte == b'\t' || byte == b'\r' || byte == b'\n' || byte == 0)
}

#[cfg(unix)]
fn open_private_cookie_file(path: &Path) -> Result<File, HttpCookieError> {
    use rustix::fs::{Mode, OFlags, open};
    use std::os::unix::fs::{MetadataExt as _, PermissionsExt as _};

    let fd = open(
        path,
        OFlags::RDONLY | OFlags::CLOEXEC | OFlags::NOFOLLOW,
        Mode::empty(),
    )
    .map_err(|_| HttpCookieError::CookieFileIo)?;
    let file = File::from(fd);
    let metadata = file.metadata().map_err(|_| HttpCookieError::CookieFileIo)?;
    if !metadata.is_file() {
        return Err(HttpCookieError::CookieFileNotRegular);
    }
    if metadata.permissions().mode() & 0o077 != 0 || metadata.nlink() != 1 {
        return Err(HttpCookieError::CookieFileInsecurePermissions);
    }
    Ok(file)
}

#[cfg(windows)]
fn open_private_cookie_file(path: &Path) -> Result<File, HttpCookieError> {
    ariax_windows_security::verify_private_file(path)
        .and_then(|()| ariax_windows_security::verify_single_link_regular_file(path))
        .map_err(|_| HttpCookieError::CookieFileInsecurePermissions)?;
    File::open(path).map_err(|_| HttpCookieError::CookieFileIo)
}

#[cfg(not(any(unix, windows)))]
fn open_private_cookie_file(_path: &Path) -> Result<File, HttpCookieError> {
    Err(HttpCookieError::CookieFileInsecurePermissions)
}

#[cfg(unix)]
fn verify_private_cookie_directory(path: &Path) -> Result<(), HttpCookieError> {
    use std::os::unix::fs::PermissionsExt as _;

    let metadata = fs::symlink_metadata(path).map_err(|_| HttpCookieError::CookieFileIo)?;
    if metadata.file_type().is_symlink() || !metadata.is_dir() {
        return Err(HttpCookieError::CookieFilePath);
    }
    if metadata.permissions().mode() & 0o077 != 0 {
        return Err(HttpCookieError::CookieFileInsecurePermissions);
    }
    Ok(())
}

#[cfg(windows)]
fn verify_private_cookie_directory(path: &Path) -> Result<(), HttpCookieError> {
    ariax_windows_security::verify_private_directory(path)
        .map_err(|_| HttpCookieError::CookieFileInsecurePermissions)
}

#[cfg(not(any(unix, windows)))]
fn verify_private_cookie_directory(_path: &Path) -> Result<(), HttpCookieError> {
    Err(HttpCookieError::CookieFileInsecurePermissions)
}

fn verify_replaceable_cookie_target(path: &Path) -> Result<(), HttpCookieError> {
    match fs::symlink_metadata(path) {
        Ok(metadata) => {
            if metadata.file_type().is_symlink() || !metadata.is_file() {
                return Err(HttpCookieError::CookieFileNotRegular);
            }
            verify_private_cookie_target(path, &metadata)
        }
        Err(error) if error.kind() == std::io::ErrorKind::NotFound => Ok(()),
        Err(_) => Err(HttpCookieError::CookieFileIo),
    }
}

#[cfg(unix)]
fn verify_private_cookie_target(
    _path: &Path,
    metadata: &fs::Metadata,
) -> Result<(), HttpCookieError> {
    use std::os::unix::fs::{MetadataExt as _, PermissionsExt as _};

    if metadata.permissions().mode() & 0o077 != 0 || metadata.nlink() != 1 {
        return Err(HttpCookieError::CookieFileInsecurePermissions);
    }
    Ok(())
}

#[cfg(windows)]
fn verify_private_cookie_target(
    path: &Path,
    _metadata: &fs::Metadata,
) -> Result<(), HttpCookieError> {
    ariax_windows_security::verify_private_file(path)
        .and_then(|()| ariax_windows_security::verify_single_link_regular_file(path))
        .map_err(|_| HttpCookieError::CookieFileInsecurePermissions)
}

#[cfg(not(any(unix, windows)))]
fn verify_private_cookie_target(
    _path: &Path,
    _metadata: &fs::Metadata,
) -> Result<(), HttpCookieError> {
    Err(HttpCookieError::CookieFileInsecurePermissions)
}

fn cookie_temporary_path(path: &Path) -> Result<PathBuf, HttpCookieError> {
    let parent = path
        .parent()
        .filter(|parent| !parent.as_os_str().is_empty())
        .ok_or(HttpCookieError::CookieFilePath)?;
    let id = COOKIE_TEMP_ID.fetch_add(1, Ordering::Relaxed);
    Ok(parent.join(format!(".ariax-cookie-{}-{id}.tmp", std::process::id())))
}

#[cfg(unix)]
fn create_private_cookie_file(path: &Path) -> Result<File, HttpCookieError> {
    use std::os::unix::fs::OpenOptionsExt as _;

    OpenOptions::new()
        .write(true)
        .create_new(true)
        .mode(0o600)
        .open(path)
        .map_err(|_| HttpCookieError::CookieFileIo)
}

#[cfg(windows)]
fn create_private_cookie_file(path: &Path) -> Result<File, HttpCookieError> {
    ariax_windows_security::create_private_file(path).map_err(|_| HttpCookieError::CookieFileIo)
}

#[cfg(not(any(unix, windows)))]
fn create_private_cookie_file(_path: &Path) -> Result<File, HttpCookieError> {
    Err(HttpCookieError::CookieFileInsecurePermissions)
}

#[cfg(unix)]
fn sync_cookie_parent(path: &Path) -> Result<(), HttpCookieError> {
    File::open(path)
        .and_then(|directory| directory.sync_all())
        .map_err(|_| HttpCookieError::CookieFileIo)
}

#[cfg(not(unix))]
fn sync_cookie_parent(_path: &Path) -> Result<(), HttpCookieError> {
    Ok(())
}

fn parse_http_url(input: &str) -> Result<Url, HttpCookieError> {
    let url = Url::parse(input).map_err(|_| HttpCookieError::InvalidUri)?;
    if !matches!(url.scheme(), "http" | "https")
        || url.host_str().is_none_or(str::is_empty)
        || !url.username().is_empty()
        || url.password().is_some()
    {
        return Err(HttpCookieError::InvalidUri);
    }
    Ok(url)
}

fn cookie_key(cookie: &Cookie<'_>) -> Result<CookieKey, HttpCookieError> {
    let domain = cookie
        .domain
        .as_cow()
        .ok_or(HttpCookieError::InvalidSetCookie)?;
    Ok(CookieKey {
        domain: domain.as_ref().to_owned().into(),
        path: String::from(&cookie.path).into(),
        name: cookie.name().to_owned().into(),
    })
}

fn rebuild_metadata(
    store: &CookieStore,
    suffixes: &List,
    previous: &BTreeMap<CookieKey, CookieMetadata>,
    sequence: u64,
    touched: Option<&CookieKey>,
) -> Result<BTreeMap<CookieKey, CookieMetadata>, HttpCookieError> {
    let mut output = BTreeMap::new();
    for cookie in store.iter_unexpired() {
        let key = cookie_key(cookie)?;
        let last_used = if touched == Some(&key) {
            sequence
        } else {
            previous.get(&key).map_or(sequence, |entry| entry.last_used)
        };
        let domain_bucket = registrable_domain(&key.domain, suffixes);
        output.insert(
            key,
            CookieMetadata {
                bytes: cookie.to_string().len(),
                domain_bucket: domain_bucket.into(),
                last_used,
            },
        );
    }
    Ok(output)
}

fn enforce_cookie_limits(
    store: &mut CookieStore,
    metadata: &mut BTreeMap<CookieKey, CookieMetadata>,
    limits: HttpCookieLimits,
) -> Result<(), HttpCookieError> {
    loop {
        let mut domains: BTreeMap<Arc<str>, (usize, usize)> = BTreeMap::new();
        for entry in metadata.values() {
            let aggregate = domains.entry(Arc::clone(&entry.domain_bucket)).or_default();
            aggregate.0 += 1;
            aggregate.1 = aggregate
                .1
                .checked_add(entry.bytes)
                .ok_or(HttpCookieError::ResourceLimit)?;
        }
        let overfull = domains.into_iter().find(|(_, (count, bytes))| {
            *count > limits.entries_per_domain || *bytes > limits.bytes_per_domain
        });
        let candidate = if let Some((domain, _)) = overfull {
            metadata
                .iter()
                .filter(|(_, entry)| entry.domain_bucket == domain)
                .min_by_key(|(_, entry)| entry.last_used)
                .map(|(key, _)| key.clone())
        } else if metadata.len() > limits.total_entries {
            metadata
                .iter()
                .min_by_key(|(_, entry)| entry.last_used)
                .map(|(key, _)| key.clone())
        } else {
            return Ok(());
        };
        let key = candidate.ok_or(HttpCookieError::ResourceLimit)?;
        store.remove(&key.domain, &key.path, &key.name);
        metadata.remove(&key);
    }
}

fn registrable_domain(host: &str, suffixes: &List) -> String {
    let canonical = host.trim_matches(['[', ']']);
    if canonical.parse::<IpAddr>().is_ok() {
        return host.to_owned();
    }
    suffixes
        .domain(canonical.as_bytes())
        .and_then(|domain| std::str::from_utf8(domain.as_bytes()).ok())
        .unwrap_or(canonical)
        .to_owned()
}

fn schemeful_site(url: &Url, suffixes: &List) -> (String, String) {
    let host = url.host_str().expect("validated URL has a host");
    (url.scheme().to_owned(), registrable_domain(host, suffixes))
}

fn same_site_cookie_allowed(
    cookie: &Cookie<'_>,
    same_site: bool,
    top_level_safe: bool,
    request: &Url,
) -> bool {
    match cookie.same_site() {
        Some(SameSite::Strict) => same_site,
        Some(SameSite::Lax) | None => same_site || top_level_safe,
        Some(SameSite::None) => cookie.secure() == Some(true) && request.scheme() == "https",
    }
}

